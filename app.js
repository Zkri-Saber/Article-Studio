function chunkManuscript(text, maxWords = 2000) {
  const paragraphs = text.split(/\n\s*\n/).map(p => p.trim()).filter(Boolean);
  const chunks = [];
  let current = [];
  let currentWords = 0;

  for (const para of paragraphs) {
    const words = para.split(/\s+/).length;
    if (current.length > 0 && currentWords + words > maxWords) {
      chunks.push(current.join("\n\n"));
      current = [para];
      currentWords = words;
    } else {
      current.push(para);
      currentWords += words;
    }
  }
  if (current.length > 0) chunks.push(current.join("\n\n"));
  return chunks;
}

analyzeBtn.addEventListener("click", async () => {
  const apiKey = apiKeyInput.value.trim();
  const text = manuscriptText.value.trim();
  const model = getActiveModelId();

  if (!apiKey) {
    setStatus("Enter your Gemini API key above before auditing.", true);
    return;
  }
  if (!text) {
    setStatus("Upload a manuscript or paste text first.", true);
    return;
  }

  analyzeBtn.disabled = true;
  progressWrap.classList.remove("hidden");
  progressFill.style.width = "0%";

  const chunks = chunkManuscript(text);
  const allFindings = [];
  const summaries = [];
  let weightedScoreSum = 0;
  let totalWords = 0;

  try {
    const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/${encodeURIComponent(model)}:generateContent`;

    for (let i = 0; i < chunks.length; i++) {
      const sectionNum = i + 1;
      const chunkWords = Math.max(1, chunks[i].split(/\s+/).length);
      setStatus(`Auditing section ${sectionNum} of ${chunks.length} (${chunkWords.toLocaleString()} words) with ${model}...`);

      const response = await fetch(endpoint, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          "x-goog-api-key": apiKey
        },
        body: JSON.stringify({
          systemInstruction: {
            parts: [{ text: SYSTEM_INSTRUCTION }]
          },
          contents: [
            {
              parts: [
                {
                  text: `Analyze section ${sectionNum} of ${chunks.length} from this manuscript for AI-favored words, transitions, filler phrases, and disembodied phrasing:\n\n${chunks[i]}`
                }
              ]
            }
          ],
          generationConfig: {
            temperature: 0.1,
            responseMimeType: "application/json",
            responseSchema: RESPONSE_SCHEMA
          }
        })
      });

      const data = await response.json();
      if (!response.ok) {
        const msg = data?.error?.message || `HTTP ${response.status}`;
        throw new Error(msg);
      }

      const rawJson = data?.candidates?.[0]?.content?.parts?.[0]?.text;
      if (!rawJson) throw new Error(`Empty response on section ${sectionNum}.`);

      const parsed = JSON.parse(rawJson);
      weightedScoreSum += parsed.ai_style_score * chunkWords;
      totalWords += chunkWords;
      summaries.push(`Section ${sectionNum}: ${parsed.section_summary}`);

      for (const item of parsed.findings) {
        allFindings.push({ section: sectionNum, ...item });
      }

      progressFill.style.width = `${Math.round((sectionNum / chunks.length) * 100)}%`;
    }

    currentReport = {
      manuscript: currentFileName,
      overall_ai_style_score: Math.round(weightedScoreSum / Math.max(1, totalWords)),
      total_words: totalWords,
      total_findings: allFindings.length,
      section_summaries: summaries,
      findings: allFindings
    };

    activeCategory = "All";
    renderReport();
    setStatus("Audit complete.");
  } catch (err) {
    setStatus(`Audit failed: ${err.message}`, true);
  } finally {
    analyzeBtn.disabled = false;
  }
});

function renderReport() {
  if (!currentReport) return;

  reportSection.classList.remove("hidden");
  const score = currentReport.overall_ai_style_score;
  scoreBadge.textContent = `AI Style Score: ${score}/100`;
  scoreBadge.style.color = score >= 65 ? "var(--danger)" : score >= 35 ? "var(--warn)" : "var(--success)";

  reportStats.textContent = `${currentReport.total_words.toLocaleString()} words audited • ${currentReport.total_findings} flagged instance(s)`;

  sectionSummaries.innerHTML = currentReport.section_summaries
    .map(s => `<p>${escapeHtml(s)}</p>`)
    .join("");

  const categories = ["All", ...new Set(currentReport.findings.map(f => f.category))];
  filterBar.innerHTML = "";
  categories.forEach(cat => {
    const count = cat === "All"
      ? currentReport.findings.length
      : currentReport.findings.filter(f => f.category === cat).length;

    const btn = document.createElement("button");
    btn.type = "button";
    btn.className = `filter-pill ${activeCategory === cat ? "active" : ""}`;
    btn.textContent = `${cat} (${count})`;
    btn.addEventListener("click", () => {
      activeCategory = cat;
      renderReport();
    });
    filterBar.appendChild(btn);
  });

  const visible = activeCategory === "All"
    ? currentReport.findings
    : currentReport.findings.filter(f => f.category === activeCategory);

  findingsList.innerHTML = visible.map((item, idx) => `
    <div class="finding">
      <div class="finding-top">
        <span class="matched-word">#${idx + 1} "${escapeHtml(item.matched_phrase)}"</span>
        <span class="cat-tag">Sec ${item.section} • ${escapeHtml(item.category)}</span>
      </div>
      <div class="detail-line"><span class="detail-label">Original:</span> ${escapeHtml(item.sentence_context)}</div>
      <div class="detail-line"><span class="detail-label">Why:</span> ${escapeHtml(item.reason)}</div>
      <div class="detail-line rewrite-text"><span class="detail-label">Rewrite:</span> ${escapeHtml(item.human_rewrite)}</div>
    </div>
  `).join("");
}

function triggerDownload(content, filename, mimeType) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

document.getElementById("downloadJsonBtn").addEventListener("click", () => {
  if (!currentReport) return;
  triggerDownload(
    JSON.stringify(currentReport, null, 2),
    `${currentFileName}_ai_audit.json`,
    "application/json"
  );
});

